export function defaultHebrewLabel(rightId) {
  const stripped = rightId.replace(/^(uk|us|de|fr|ca|au|ie|nl|es|it|se|pl)_/i, "");
  const tokens = stripped.split("_").filter((t) => t.length > 1 && !/^\d+$/.test(t));
  const parts = [];
  for (const t of tokens) {
    const he = SEG_HE[t];
    if (he && he.length > 0) parts.push(he);
  }
  const unique = [...new Set(parts)];
  if (unique.length >= 1) return unique.slice(0, 4).join(" · ");
  return "זכות בינלאומית";
}
