const TOOL_EN = {
  "/flights": "Flight compensation (EU261)",
  "/scan": "Recurring charge scan",
  "/cancel": "Cancel subscription",
  "/bank-fees": "Bank fees — agent",
  "/money": "Agent — bill negotiation",
};

const rows = {};

for (const market of allMarkets()) {
  if (market.code === "IL") continue;
  for (const right of market.pack.rights) {
    const key = `${market.code}:${right.id}`;
    if (right.action.kind === "tool" && right.action.tool) {
      const tool = right.action.tool;
      rows[key] = {
        en: TOOL_EN[tool] ?? humanize(right.id),
        he: TOOL_HE[tool] ?? humanize(right.id),
      };
      continue;
    }
    rows[key] = {
      en: humanize(right.id),
      he: HE_OVERRIDES[right.id] ?? humanize(right.id),
    };
  }
}

const sorted = Object.keys(rows).sort();
let out = `/** AUTO-GENERATED by scripts/generate-pack-labels.mjs — do not edit by hand */\n\n`;
out += `export type PackLabelRow = { en: string; he: string };\n\n`;
out += `export const PACK_RIGHT_LABELS: Record<string, PackLabelRow> = {\n`;
for (const key of sorted) {
  const { en, he } = rows[key];
  out += `  ${JSON.stringify(key)}: { en: ${JSON.stringify(en)}, he: ${JSON.stringify(he)} },\n`;
}
out += `};\n`;

writeFileSync("src/lib/global/packLabels.generated.ts", out);
console.log(`Wrote ${sorted.length} pack right labels`);
